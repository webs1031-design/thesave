// src/regions.ts

export type RegionNode = {
  name: string;
  children?: RegionNode[];
};

export type RegionData = {
  서울: RegionNode[];
  경기: RegionNode[];
  인천: RegionNode[];
};

/**
 * 이름 여러 개를 간단하게 RegionNode[]로 변환
 */
function leaves(names: string): RegionNode[] {
  return names
    .trim()
    .split(/\s+/)
    .filter(Boolean)
    .map((name) => ({ name }));
}

/**
 * 상위 지역 + 하위 지역 생성
 */
function group(
  name: string,
  children: string | RegionNode[]
): RegionNode {
  return {
    name,
    children:
      typeof children === "string"
        ? leaves(children)
        : children,
  };
}

