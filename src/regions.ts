/**
 * 하위 지역 가져오기
 *
 * 예:
 *
 * getChildren(["서울"])
 * → 서울의 구
 *
 * getChildren(["서울", "강남구"])
 * → 강남구의 동
 *
 * getChildren(["경기", "고양시"])
 * → 덕양구 / 일산동구 / 일산서구
 *
 * getChildren(["경기", "고양시", "덕양구"])
 * → 덕양구의 동
 */
export function getChildren(
  path: string[]
): RegionNode[] {
  if (path.length === 0) {
    return [];
  }

  const city =
    path[0] as keyof RegionData;

  let current: RegionNode[] =
    regions[city] ?? [];

  for (
    let i = 1;
    i < path.length;
    i++
  ) {
    const target = current.find(
      (item) =>
        item.name === path[i]
    );

    if (!target) {
      return [];
    }

    current =
      target.children ?? [];
  }

  return current;
}

/**
 * 해당 지역 경로가 존재하는지 확인
 */
export function isValidRegion(
  path: string[]
): boolean {
  if (path.length === 0) {
    return false;
  }

  const city =
    path[0] as keyof RegionData;

  if (!regions[city]) {
    return false;
  }

  if (path.length === 1) {
    return true;
  }

  let current: RegionNode[] =
    regions[city];

  for (
    let i = 1;
    i < path.length;
    i++
  ) {
    const target = current.find(
      (item) =>
        item.name === path[i]
    );

    if (!target) {
      return false;
    }

    current =
      target.children ?? [];
  }

  return true;
}

/**
 * URL 만들기
 *
 * 예:
 *
 * makeRegionUrl([
 *   "서울",
 *   "강남구",
 *   "역삼동"
 * ])
 *
 * → /서울/강남구/역삼동
 */
export function makeRegionUrl(
  path: string[]
): string {
  return `/${path
    .map((item) =>
      encodeURIComponent(item)
    )
    .join("/")}`;
}

/**
 * URL의 한글 지역명 복원
 */
export function decodeRegion(
  value: string
): string {
  try {
    return decodeURIComponent(
      value
    );
  } catch {
    return value;
  }
}

/**
 * 지원 지역 확인
 */
export function isSupportedCity(
  value: string
): boolean {
  const city =
    decodeRegion(value);

  return (
    city === "서울" ||
    city === "경기" ||
    city === "인천"
  );
}

